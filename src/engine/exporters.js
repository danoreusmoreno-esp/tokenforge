const kebab = (s) => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '');
const fontStack = (name) =>
  `'${name}', ${/Mono/.test(name) ? 'ui-monospace, monospace' : /Serif|Fraunces|Playfair/.test(name) ? 'Georgia, serif' : 'system-ui, sans-serif'}`;

/** Flat map of CSS custom properties for one appearance + viewport. */
export function cssVars(sys, appearance = 'light', viewport = 'desktop', components = []) {
  const ap = sys.appearances[appearance];
  const v = {};
  for (const fam of sys.families) ap.ramps[fam].forEach((hex, i) => (v[`--color-${fam}-${i + 1}`] = hex));
  for (const [k, hex] of Object.entries(ap.roles)) v[`--${k}`] = hex;
  for (const [k, px] of Object.entries(sys.spacing)) v[`--space-${k}`] = `${px}px`;
  for (const [k, px] of Object.entries(sys.layout[viewport])) v[`--${k}`] = `${px}px`;
  for (const [k, px] of Object.entries(sys.radius)) v[`--radius-${k}`] = `${px}px`;
  for (const [k, s] of Object.entries(ap.shadow)) v[`--shadow-${k}`] = s;
  for (const [name, t] of Object.entries(sys.type[viewport])) {
    v[`--text-${name}-size`] = `${t.size}px`;
    v[`--text-${name}-line-height`] = `${t.lineHeightPx}px`;
    v[`--text-${name}-weight`] = String(t.weight);
    v[`--text-${name}-tracking`] = `${t.tracking}em`;
  }
  v['--font-body'] = fontStack(sys.fonts.body);
  v['--font-heading'] = fontStack(sys.fonts.heading);
  v['--font-mono'] = fontStack(sys.fonts.mono);
  v['--duration-fast'] = `${sys.motion.fast}ms`;
  v['--duration-base'] = `${sys.motion.base}ms`;
  v['--duration-slow'] = `${sys.motion.slow}ms`;
  v['--ease-standard'] = sys.motion.ease;
  for (const c of components) {
    const t = componentTokens(sys, c);
    for (const [k, val] of Object.entries(t)) v[`--${c}-${k}`] = val;
  }
  return v;
}

/** Component tokens merge catalogue defaults with brand overrides. */
export function componentTokens(sys, id) {
  const def = COMPONENTS.find((c) => c.id === id);
  if (!def) return {};
  const overrides = sys.brand.componentTokens?.[id] ?? {};
  const out = {};
  for (const [k, val] of Object.entries({ ...def.tokens, ...overrides })) {
    out[k] = typeof val === 'number' && !/weight|rows/.test(k) ? `${val}px` : String(val);
  }
  return out;
}

const block = (sel, vars) => `${sel} {\n${Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`).join('\n')}\n}`;

function cssCore(sys) {
  const comps = sys.brand.components ?? [];
  const light = cssVars(sys, 'light', 'desktop', comps);
  const dark = cssVars(sys, 'dark', 'desktop');
  const darkOnly = {};
  // Everything that changes with the theme: ramps, colour roles (text-* roles included) and shadows.
  const themed = new Set(Object.keys(sys.appearances.dark.roles).map((r) => `--${r}`));
  for (const k of Object.keys(dark)) if (k.startsWith('--color-') || k.startsWith('--shadow-') || themed.has(k)) darkOnly[k] = dark[k];
  const vpVars = (vp) => {
    const o = {};
    for (const [k, px] of Object.entries(sys.layout[vp])) o[`--${k}`] = `${px}px`;
    for (const [name, t] of Object.entries(sys.type[vp])) {
      if (t.size !== sys.type.desktop[name].size) {
        o[`--text-${name}-size`] = `${t.size}px`;
        o[`--text-${name}-line-height`] = `${t.lineHeightPx}px`;
      }
    }
    return o;
  };
  return [
    `/* ${sys.brand.name} — design tokens. Generated by Tokenforge. */`,
    block(':root', light),
    block(`[data-theme="dark"]`, darkOnly),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme="light"])', darkOnly).replace(/^/gm, '  ')}\n}`,
    `@media (max-width: 1024px) {\n${block(':root', vpVars('tablet')).replace(/^/gm, '  ')}\n}`,
    `@media (max-width: 640px) {\n${block(':root', vpVars('mobile')).replace(/^/gm, '  ')}\n}`,
  ].join('\n\n');
}

/** W3C Design Tokens Community Group format, with light/dark as $extensions modes. */
function dtcgCore(sys) {
  const L = sys.appearances.light;
  const D = sys.appearances.dark;
  const modes = (l, d) => ({ $extensions: { modes: { light: l, dark: d } } });
  const out = { $description: `${sys.brand.name} design tokens`, color: {}, role: {}, space: {}, radius: {}, shadow: {}, typography: {}, font: {}, motion: {}, layout: {}, component: {} };
  for (const fam of sys.families) {
    out.color[fam] = {};
    L.ramps[fam].forEach((hex, i) => (out.color[fam][i + 1] = { $type: 'color', $value: hex, ...modes(hex, D.ramps[fam][i]) }));
  }
  for (const k of Object.keys(L.roles)) out.role[k] = { $type: 'color', $value: L.roles[k], ...modes(L.roles[k], D.roles[k]) };
  for (const [k, px] of Object.entries(sys.spacing)) out.space[k] = { $type: 'dimension', $value: `${px}px` };
  for (const [k, px] of Object.entries(sys.radius)) out.radius[k] = { $type: 'dimension', $value: `${px}px` };
  for (const k of Object.keys(L.shadow)) out.shadow[k] = { $type: 'shadow', $value: L.shadow[k], ...modes(L.shadow[k], D.shadow[k]) };
  out.font = {
    body: { $type: 'fontFamily', $value: sys.fonts.body },
    heading: { $type: 'fontFamily', $value: sys.fonts.heading },
    mono: { $type: 'fontFamily', $value: sys.fonts.mono },
  };
  for (const [name, t] of Object.entries(sys.type.desktop)) {
    out.typography[name] = {
      $type: 'typography',
      $value: { fontFamily: name === 'display' || name.startsWith('h') ? '{font.heading}' : '{font.body}', fontSize: `${t.size}px`, lineHeight: `${t.lineHeightPx}px`, fontWeight: t.weight, letterSpacing: `${t.tracking}em` },
      $extensions: { viewports: { tablet: `${sys.type.tablet[name].size}px`, mobile: `${sys.type.mobile[name].size}px` } },
    };
  }
  out.motion = {
    fast: { $type: 'duration', $value: `${sys.motion.fast}ms` },
    base: { $type: 'duration', $value: `${sys.motion.base}ms` },
    slow: { $type: 'duration', $value: `${sys.motion.slow}ms` },
    ease: { $type: 'cubicBezier', $value: sys.motion.ease },
  };
  for (const [k, px] of Object.entries(sys.layout.desktop)) {
    out.layout[k] = { $type: 'dimension', $value: `${px}px`, $extensions: { viewports: { tablet: `${sys.layout.tablet[k]}px`, mobile: `${sys.layout.mobile[k]}px` } } };
  }
  for (const id of sys.brand.components ?? []) {
    const t = componentTokens(sys, id);
    if (!Object.keys(t).length) continue;
    out.component[id] = {};
    for (const [k, v] of Object.entries(t)) out.component[id][k] = { $type: /px$/.test(v) ? 'dimension' : 'number', $value: v };
  }
  return out;
}

/** Tokens Studio for Figma (multi-file sets: global, light, dark). Import into Figma Variables. */
function figmaCore(sys) {
  const L = sys.appearances.light;
  const D = sys.appearances.dark;
  const set = (ap) => {
    const o = { color: {}, role: {} };
    for (const fam of sys.families) {
      o.color[fam] = {};
      ap.ramps[fam].forEach((hex, i) => (o.color[fam][i + 1] = { value: hex, type: 'color' }));
    }
    for (const [k, hex] of Object.entries(ap.roles)) o.role[k] = { value: hex, type: 'color' };
    return o;
  };
  const global = { space: {}, radius: {}, fontFamilies: {}, fontSize: {}, lineHeight: {}, fontWeight: {}, typography: {} };
  for (const [k, px] of Object.entries(sys.spacing)) global.space[k] = { value: String(px), type: 'spacing' };
  for (const [k, px] of Object.entries(sys.radius)) global.radius[k] = { value: String(px), type: 'borderRadius' };
  global.fontFamilies = { body: { value: sys.fonts.body, type: 'fontFamilies' }, heading: { value: sys.fonts.heading, type: 'fontFamilies' }, mono: { value: sys.fonts.mono, type: 'fontFamilies' } };
  for (const [name, t] of Object.entries(sys.type.desktop)) {
    global.fontSize[name] = { value: String(t.size), type: 'fontSizes' };
    global.lineHeight[name] = { value: String(t.lineHeightPx), type: 'lineHeights' };
    global.fontWeight[name] = { value: String(t.weight), type: 'fontWeights' };
    const fam = name === 'display' || name.startsWith('h') ? '{fontFamilies.heading}' : '{fontFamilies.body}';
    global.typography[name] = { type: 'typography', value: { fontFamily: fam, fontSize: `{fontSize.${name}}`, lineHeight: `{lineHeight.${name}}`, fontWeight: `{fontWeight.${name}}` } };
  }
  return {
    global,
    light: set(L),
    dark: set(D),
    $themes: [
      { id: 'light', name: 'Light', selectedTokenSets: { global: 'source', light: 'enabled' } },
      { id: 'dark', name: 'Dark', selectedTokenSets: { global: 'source', dark: 'enabled' } },
    ],
    $metadata: { tokenSetOrder: ['global', 'light', 'dark'] },
    _set: set,
  };
}

export function toTailwind(sys0) {
  const sys = family(sys0).m;
  const colors = {};
  for (const fam of sys.families) {
    colors[fam] = {};
    for (let i = 1; i <= 12; i++) colors[fam][i] = `var(--color-${fam}-${i})`;
  }
  for (const k of Object.keys(sys.appearances.light.roles)) colors[k] = `var(--${k})`;
  const spacing = {};
  for (const k of Object.keys(sys.spacing)) spacing[k] = `var(--space-${k})`;
  const fontSize = {};
  for (const name of Object.keys(sys.type.desktop)) fontSize[name] = [`var(--text-${name}-size)`, { lineHeight: `var(--text-${name}-line-height)`, fontWeight: `var(--text-${name}-weight)` }];
  const cfg = {
    darkMode: ['selector', '[data-theme="dark"]'],
    theme: {
      extend: {
        colors,
        spacing,
        fontSize,
        borderRadius: { box: 'var(--radius-boxes)', field: 'var(--radius-fields)', selector: 'var(--radius-selectors)' },
        boxShadow: { sm: 'var(--shadow-sm)', md: 'var(--shadow-md)', lg: 'var(--shadow-lg)' },
        fontFamily: { body: 'var(--font-body)', heading: 'var(--font-heading)', mono: 'var(--font-mono)' },
        transitionDuration: { fast: 'var(--duration-fast)', base: 'var(--duration-base)', slow: 'var(--duration-slow)' },
      },
    },
  };
  return `// tailwind.config.js — ${sys.brand.name}. Load tokens.css first.\n/** @type {import('tailwindcss').Config} */\nexport default ${JSON.stringify(cfg, null, 2)};\n`;
}

